CREATE TABLE IF NOT EXISTS roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL UNIQUE,
    descripcion VARCHAR(255),
    activo SMALLINT NOT NULL DEFAULT 1 CHECK (activo IN (0, 1)),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE roles
    ADD COLUMN IF NOT EXISTS activo SMALLINT NOT NULL DEFAULT 1 CHECK (activo IN (0, 1));

CREATE TABLE IF NOT EXISTS permisos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS rol_permiso (
    rol_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    permiso_id BIGINT NOT NULL REFERENCES permisos(id) ON DELETE CASCADE,
    PRIMARY KEY (rol_id, permiso_id)
);

CREATE TABLE IF NOT EXISTS carreras (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    abreviatura VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS semestres (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero SMALLINT NOT NULL UNIQUE CHECK (numero > 0)
);

CREATE TABLE IF NOT EXISTS periodos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO' CHECK (estado IN ('ACTIVO', 'CERRADO')),
    ya_editado SMALLINT NOT NULL DEFAULT 0 CHECK (ya_editado IN (0, 1)),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (fecha_fin >= fecha_inicio)
);

CREATE TABLE IF NOT EXISTS clubs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('CULTURAL', 'DEPORTIVO')),
    descripcion VARCHAR(255),
    cupo_limite SMALLINT NOT NULL CHECK (cupo_limite BETWEEN 1 AND 50),
    id_responsable BIGINT,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL,
    apellidop VARCHAR(50) NOT NULL,
    apellidom VARCHAR(50) NOT NULL DEFAULT '',
    numerocontrol VARCHAR(8),
    telefono VARCHAR(15),
    carrera_id BIGINT REFERENCES carreras(id) ON DELETE SET NULL,
    semestre_id BIGINT REFERENCES semestres(id) ON DELETE SET NULL,
    usuario VARCHAR(8) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('OFICINA', 'MONITOR')),
    club_asignado BIGINT REFERENCES clubs(id) ON DELETE SET NULL,
    foto VARCHAR(255),
    rol_id BIGINT REFERENCES roles(id) ON DELETE SET NULL,
    creado_por BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    cambio_password_requerido SMALLINT NOT NULL DEFAULT 0 CHECK (cambio_password_requerido IN (0, 1)),
    activo SMALLINT NOT NULL DEFAULT 1 CHECK (activo IN (0, 1)),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT usuarios_numero_control_unico UNIQUE (numerocontrol)
);

DO $$
