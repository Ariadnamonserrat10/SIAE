CREATE TABLE IF NOT EXISTS usuario_club (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    club_id BIGINT NOT NULL REFERENCES clubs(id) ON DELETE CASCADE,
    fecha_asignacion DATE NOT NULL DEFAULT CURRENT_DATE,
    activo SMALLINT NOT NULL DEFAULT 1 CHECK (activo IN (0, 1)),
    asignado_por BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    CONSTRAINT usuario_club_usuario_club_unico UNIQUE (usuario_id, club_id)
);

CREATE TABLE IF NOT EXISTS alumnos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL,
    apellidop VARCHAR(50) NOT NULL,
    apellidom VARCHAR(50) NOT NULL DEFAULT '',
    numerocontrol VARCHAR(8) NOT NULL,
    telefono VARCHAR(15) NOT NULL,
    carrera_id BIGINT REFERENCES carreras(id) ON DELETE SET NULL,
    semestre_id BIGINT REFERENCES semestres(id) ON DELETE SET NULL,
    id_club BIGINT REFERENCES clubs(id) ON DELETE SET NULL,
    periodo_id BIGINT NOT NULL REFERENCES periodos(id) ON DELETE RESTRICT,
    estado_periodo VARCHAR(20) NOT NULL DEFAULT 'ACTIVO'
        CHECK (estado_periodo IN ('ACTIVO', 'ACREDITADO', 'REPROBADO')),
    opcion_1 VARCHAR(100),
    opcion_2 VARCHAR(100),
    opcion_3 VARCHAR(100),
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT alumnos_control_periodo_unico UNIQUE (numerocontrol, periodo_id)
);

CREATE TABLE IF NOT EXISTS asistencias (
    id_alumno BIGINT NOT NULL REFERENCES alumnos(id) ON DELETE CASCADE,
    fecha DATE NOT NULL,
    presente SMALLINT NOT NULL DEFAULT 0 CHECK (presente IN (0, 1)),
    PRIMARY KEY (id_alumno, fecha)
);

CREATE TABLE IF NOT EXISTS fechas_club (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    periodo_id BIGINT NOT NULL REFERENCES periodos(id) ON DELETE CASCADE,
    club_id BIGINT NOT NULL REFERENCES clubs(id) ON DELETE CASCADE,
    fecha DATE NOT NULL,
    creado_por BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fechas_club_periodo_club_fecha_unico UNIQUE (periodo_id, club_id, fecha)
);

CREATE TABLE IF NOT EXISTS datos_medicos_basicos (
    alumno_id BIGINT PRIMARY KEY REFERENCES alumnos(id) ON DELETE CASCADE,
    alergias TEXT,
    restricciones_fisicas TEXT,
    condicion_emergencia TEXT,
    contacto_emergencia VARCHAR(150),
    telefono_emergencia VARCHAR(15),
    observaciones TEXT,
    actualizado_por BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS documentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio VARCHAR(40) NOT NULL UNIQUE,
    tipo VARCHAR(30) NOT NULL CHECK (tipo IN ('PAGO', 'REPOSICION_CONSTANCIA', 'MATERIAL', 'OTRO')),
    alumno_id BIGINT REFERENCES alumnos(id) ON DELETE SET NULL,
    club_id BIGINT REFERENCES clubs(id) ON DELETE SET NULL,
    periodo_id BIGINT REFERENCES periodos(id) ON DELETE SET NULL,
    nombre_original VARCHAR(255) NOT NULL,
    nombre_archivo VARCHAR(255) NOT NULL UNIQUE,
    mime_type VARCHAR(100) NOT NULL,
    tamano_bytes BIGINT NOT NULL CHECK (tamano_bytes >= 0),
    hash_sha256 CHAR(64) NOT NULL UNIQUE,
    concepto VARCHAR(255),
    monto NUMERIC(10, 2) CHECK (monto IS NULL OR monto >= 0),
    creado_por BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO' CHECK (estado IN ('ACTIVO', 'ANULADO')),
    formato_codigo VARCHAR(20),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS evaluaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alumno_id BIGINT NOT NULL REFERENCES alumnos(id) ON DELETE CASCADE,
    periodo_id BIGINT NOT NULL REFERENCES periodos(id) ON DELETE CASCADE,
    escala_version SMALLINT NOT NULL DEFAULT 2,
    formato_documento_id BIGINT REFERENCES documentos(id) ON DELETE SET NULL,
    nombre_estudiante VARCHAR(155) NOT NULL,
    nombre_club VARCHAR(100) NOT NULL,
    periodo_realizacion DATE NOT NULL,
    criterio_1 SMALLINT NOT NULL CHECK (criterio_1 BETWEEN 0 AND 4),
    criterio_2 SMALLINT NOT NULL CHECK (criterio_2 BETWEEN 0 AND 4),
    criterio_3 SMALLINT NOT NULL CHECK (criterio_3 BETWEEN 0 AND 4),
    criterio_4 SMALLINT NOT NULL CHECK (criterio_4 BETWEEN 0 AND 4),
    criterio_5 SMALLINT NOT NULL CHECK (criterio_5 BETWEEN 0 AND 4),
    criterio_6 SMALLINT NOT NULL CHECK (criterio_6 BETWEEN 0 AND 4),
    criterio_7 SMALLINT NOT NULL CHECK (criterio_7 BETWEEN 0 AND 4),
    observaciones VARCHAR(2000) NOT NULL DEFAULT '',
    valor_numerico NUMERIC(5, 2) NOT NULL,
    nivel_desempeno VARCHAR(50) NOT NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS app_config (
    clave VARCHAR(150) PRIMARY KEY,
    valor TEXT NOT NULL,
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS historial_configuracion (
    periodo_id BIGINT NOT NULL REFERENCES periodos(id) ON DELETE CASCADE,
    clave VARCHAR(150) NOT NULL,
    valor TEXT NOT NULL,
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (periodo_id, clave)
);

CREATE TABLE IF NOT EXISTS filtros_cerrados (
    periodo_id BIGINT NOT NULL REFERENCES periodos(id) ON DELETE CASCADE,
    tipo VARCHAR(50) NOT NULL,
    cerrado_por BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    cerrado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (periodo_id, tipo)
);

CREATE TABLE IF NOT EXISTS tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    selector VARCHAR(64) NOT NULL UNIQUE,
    token VARCHAR(255) NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    activo SMALLINT NOT NULL DEFAULT 1 CHECK (activo IN (0, 1)),
    ip VARCHAR(64),
    user_agent VARCHAR(512),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS login_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ip VARCHAR(64) NOT NULL,
    usuario VARCHAR(100) NOT NULL,
    success SMALLINT NOT NULL CHECK (success IN (0, 1)),
    attempt_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS auditoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    accion VARCHAR(100) NOT NULL,
    descripcion TEXT,
    fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS materiales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    descripcion TEXT,
    cantidad_total INTEGER NOT NULL DEFAULT 0 CHECK (cantidad_total >= 0),
    cantidad_disponible INTEGER NOT NULL DEFAULT 0 CHECK (cantidad_disponible >= 0),
    club_id BIGINT REFERENCES clubs(id) ON DELETE SET NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'AGOTADO' CHECK (estado IN ('DISPONIBLE', 'AGOTADO', 'BAJA')),
    creado_por BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (cantidad_disponible <= cantidad_total)
);

CREATE TABLE IF NOT EXISTS movimientos_material (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id BIGINT NOT NULL REFERENCES materiales(id) ON DELETE CASCADE,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('ENTRADA', 'SALIDA', 'AJUSTE')),
    cantidad INTEGER NOT NULL CHECK (cantidad >= 0),
    motivo VARCHAR(255) NOT NULL,
    documento_id BIGINT REFERENCES documentos(id) ON DELETE SET NULL,
    usuario_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS alumnos_periodo_club_idx ON alumnos(periodo_id, id_club);
CREATE INDEX IF NOT EXISTS usuarios_club_activo_idx ON usuarios(club_asignado, activo);
CREATE INDEX IF NOT EXISTS usuario_club_activo_idx ON usuario_club(usuario_id, activo);
CREATE INDEX IF NOT EXISTS asistencias_fecha_idx ON asistencias(fecha);
CREATE INDEX IF NOT EXISTS evaluaciones_alumno_periodo_idx ON evaluaciones(alumno_id, periodo_id);
CREATE INDEX IF NOT EXISTS documentos_estado_tipo_idx ON documentos(estado, tipo);
CREATE INDEX IF NOT EXISTS tokens_usuario_sesion_idx ON tokens(user_id, tipo, activo, expires_at);
CREATE INDEX IF NOT EXISTS login_attempts_ip_usuario_fecha_idx ON login_attempts(ip, usuario, attempt_time);
CREATE INDEX IF NOT EXISTS auditoria_fecha_idx ON auditoria(fecha DESC);
CREATE INDEX IF NOT EXISTS movimientos_material_material_fecha_idx ON movimientos_material(material_id, creado_en DESC);

